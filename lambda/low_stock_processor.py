"""AWS Lambda Function: Serverless Low-Stock Processor & Notification Dispatcher.

This function can be triggered:
1. Daily via Amazon EventBridge (CloudWatch Events) schedule to send a morning stock summary digest.
2. Directly via AWS SNS or API Gateway when inventory updates occur.
"""

import json
import logging
import os
import boto3
from botocore.exceptions import ClientError

logger = logging.getLogger()
logger.setLevel(logging.INFO)

sns_client = boto3.client('sns', region_name=os.environ.get('AWS_REGION', 'us-east-1'))


def lambda_handler(event, context):
    """Entry point for AWS Lambda."""
    topic_arn = os.environ.get('SNS_TOPIC_ARN', '').strip()
    logger.info(f"Received Lambda event: {json.dumps(event)}")

    if not topic_arn:
        logger.error("SNS_TOPIC_ARN environment variable is missing.")
        return {
            'statusCode': 500,
            'body': json.dumps({'error': 'SNS_TOPIC_ARN is not configured'})
        }

    # Extract products payload from event (if passed via API Gateway / EventBridge)
    products_to_check = event.get('products', [])

    # If event has a direct single-product alert trigger
    if 'product_name' in event:
        products_to_check = [event]

    if not products_to_check:
        logger.info("No explicit products passed in event payload.")
        return {
            'statusCode': 200,
            'body': json.dumps({'message': 'Scan completed. No products provided in event payload.'})
        }

    low_stock_list = []
    for item in products_to_check:
        qty = int(item.get('quantity', 0))
        min_level = int(item.get('min_stock_level', 5))
        if qty <= min_level:
            low_stock_list.append(item)

    if not low_stock_list:
        logger.info("All products are above minimum threshold. No alert needed.")
        return {
            'statusCode': 200,
            'body': json.dumps({'message': 'All stock levels healthy. Zero alerts dispatched.'})
        }

    # Format multi-product digest alert
    subject = f"⚠️ [AWS LAMBDA ALERT] {len(low_stock_list)} Products Require Reorder!"
    message_lines = [
        "DAILY INVENTORY STATUS REPORT - LOW STOCK DIGEST",
        "============================================================",
        f"Generated by: AWS Lambda ({context.function_name if context else 'Local'})",
        f"Total Critical Items: {len(low_stock_list)}",
        "------------------------------------------------------------",
    ]

    for p in low_stock_list:
        message_lines.append(
            f"• {p.get('name', 'Unknown')} (SKU: {p.get('sku', 'N/A')}) | "
            f"Current Stock: {p.get('quantity', 0)} | Min Level: {p.get('min_stock_level', 5)}"
        )

    message_lines.append("============================================================")
    message_lines.append("Please log in to your dashboard to restock these items.")

    full_message = "\n".join(message_lines)

    try:
        response = sns_client.publish(
            TopicArn=topic_arn,
            Subject=subject[:100],
            Message=full_message
        )
        message_id = response.get('MessageId')
        logger.info(f"Published alert {message_id} to {topic_arn}")
        return {
            'statusCode': 200,
            'body': json.dumps({
                'status': 'success',
                'message_id': message_id,
                'items_alerted': len(low_stock_list)
            })
        }
    except ClientError as e:
        logger.error(f"Error publishing to SNS: {e}")
        return {
            'statusCode': 500,
            'body': json.dumps({'error': str(e)})
        }
